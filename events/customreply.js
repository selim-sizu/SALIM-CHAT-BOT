// ট্রিগার চেক (ছোট হাতের অক্ষরে, বর্ডার স্পেস বাদ)
function normalize(text) {
  return String(text).trim().toLowerCase();
}

module.exports = {
  config: {
    eventType: "message",
    name: "customreply"
  },

  run: async ({ api, event, config }) => {
    if (!event || !event.body || !event.threadID) return;

    const text = normalize(event.body);

    // কমান্ড হলে বাদ দাও (prefix দিয়ে শুরু হলে)
    if (config.prefix && event.body.trim().startsWith(config.prefix)) return;

    // বট নিজেই হলে বাদ দাও (লুপ এড়াতে)
    if (event.senderID === api.getCurrentUserID()) return;

    // হুবহু ম্যাচ
    if (REPLIES[text]) {
      const value = REPLIES[text];
      const reply = Array.isArray(value) ? pickRandom(value) : value;
      return sendSafe(api, event.threadID, reply);
    }

    // আংশিক ম্যাচ (ট্রিগার থাকলে রিপ্লাই)
    for (const trigger of Object.keys(REPLIES)) {
      if (trigger.length < 2) continue; // ১ অক্ষরের ট্রিগার skip (যেমন 💋 আলাদা হ্যান্ডেল)
      if (text === trigger) continue;
      // word boundary ম্যাচ
      const re = new RegExp(`(^|\\s)${trigger.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}($|\\s)`, "i");
      if (re.test(text)) {
        const value = REPLIES[trigger];
        const reply = Array.isArray(value) ? pickRandom(value) : value;
        return sendSafe(api, event.threadID, reply);
      }
    }
  }
};
