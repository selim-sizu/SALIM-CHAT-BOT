// ছোট হাতের + trim + একাধিক স্পেস এক
function normalize(t) {
  return String(t || "").trim().toLowerCase().replace(/\s+/g, " ");
}

module.exports = {
  config: {
    eventType: "message",
    name: "autoreply"
  },

  run: async ({ api, event, config }) => {
    if (!event?.body || !event?.threadID) return;

    // কমান্ড হলে বাদ
    if (config?.prefix && event.body.trim().startsWith(config.prefix)) return;

    // নিজের মেসেজ হলে বাদ (loop এড়াতে)
    if (event.senderID === api.getCurrentUserID()) return;

    const text = normalize(event.body);

    // ১) হুবহু ম্যাচ
    if (REPLIES[text]) {
      const v = REPLIES[text];
      return sendSafe(
        api,
        event.threadID,
        Array.isArray(v) ? pickRandom(v) : v,
        event.messageID
      );
    }

    // ২) বাক্যের ভেতরে ট্রিগার (৩+ অক্ষরের key)
    for (const key of Object.keys(REPLIES)) {
      if (key.length < 3) continue;
      const re = new RegExp(
        `(^|\\s)${key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}($|\\s)`,
        "i"
      );
      if (re.test(text)) {
        const v = REPLIES[key];
        return sendSafe(
          api,
          event.threadID,
          Array.isArray(v) ? pickRandom(v) : v,
          event.messageID
        );
      }
    }
  }
};
